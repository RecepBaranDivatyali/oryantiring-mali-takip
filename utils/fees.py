@st.fragment
def render_fees_page(store, categories, invalidate_cb, today_date, default_tab=None, transactions=None):
    ok, err = store.ensure()
    if not ok:
        st.error("Ücret takibi tabloları Supabase'de henüz yok (ya da bağlantı kurulamadı).")
        st.code(SUPABASE_SQL, language="sql")
        st.caption(f"Teknik ayrıntı: {err}")
        return

    income_cats = [c for c in categories if c.get("type") == "Gelir"]
    kademeler = store.kademeler()
    k_map = {k["id"]: k for k in kademeler}
    all_members_list = store.members()
    all_mem_map = {m["id"]: m["name"] for m in all_members_list}

    if default_tab == "kademeler":
        tab_kademe, tab_pay, tab_fee, tab_mem = st.tabs(
            ["🏕️ Kademeler", "✅ Ödeme Takibi", "🧾 Ücret Kalemleri", "👥 Sporcular"]
        )
    else:
        tab_pay, tab_fee, tab_kademe, tab_mem = st.tabs(
            ["✅ Ödeme Takibi", "🧾 Ücret Kalemleri", "🏕️ Kademeler", "👥 Sporcular"]
        )

    # ------------------------------------------------ 1. Ödeme Takibi
    with tab_pay:
        items = store.fee_items()
        if not items:
            st.info("Henüz ücret kalemi yok. **🧾 Ücret Kalemleri** sekmesinden ekleyin.")
        else:
            p_hdr1, p_hdr2 = st.columns([3, 1])
            fee = p_hdr1.selectbox(
                "Ücret kalemi seçin",
                items,
                format_func=lambda f: f"{f['name']} — {_fee_price_summary(f)}",
                key="fees_pay_item",
            )
            tariffs = fee.get("tariffs") or []
            rows = store.assignments(fee["id"])

            with p_hdr2:
                st.markdown("<div style='height: 27px;'></div>", unsafe_allow_html=True)
                with st.popover("➕ Sporcu Ekle", use_container_width=True):
                    assigned_ids_pay = {r["member_id"] for r in rows}
                    free_pay = [m for m in all_members_list if m["id"] not in assigned_ids_pay]
                    if not free_pay:
                        st.info("Tüm kayıtlı sporcular zaten bu kaleme atanmış.")
                    else:
                        add_pay_sel = st.multiselect(
                            "Eklenecek Sporcular",
                            [m["id"] for m in free_pay],
                            format_func=lambda i: all_mem_map[i],
                            key=f"pay_tab_add_{fee['id']}",
                        )
                        pay_custom_amt = None
                        if tariffs:
                            pay_t_idx = st.selectbox(
                                "Başlangıç Tarifesi",
                                options=range(len(tariffs)),
                                format_func=lambda idx: _tariff_option_label(tariffs[idx]),
                                key=f"pay_tab_add_tariff_{fee['id']}",
                            )
                            pay_custom_amt = float(tariffs[pay_t_idx]["amount"])
                        if st.button("➕ Seçilenleri Ata", type="primary", use_container_width=True, key=f"pay_tab_add_btn_{fee['id']}"):
                            if add_pay_sel:
                                n_new = store.assign(fee["id"], add_pay_sel, custom_amount=pay_custom_amt)
                                st.toast(f"✅ {n_new} sporcu eklendi.")
                                st.rerun(scope="fragment")
                            else:
                                st.warning("Lütfen en az bir sporcu seçin.")

            if not rows:
                st.info("Bu kaleme henüz sporcu atanmamış. Sağ üstteki **➕ Sporcu Ekle** veya aşağıdaki kademe butonundan atayabilirsiniz.")
                if kademeler:
                    q_col1, q_col2 = st.columns([2, 1])
                    q_kid = q_col1.selectbox(
                        "Kademeden Hızlı Ata",
                        list(k_map.keys()),
                        format_func=lambda kid: f"🏕️ {k_map[kid]['name']} ({len(k_map[kid]['member_ids'])} sporcu)",
                        key=f"quick_kademe_assign_{fee['id']}",
                    )
                    if q_col2.button("⚡ Kafileyi Ata", type="primary", use_container_width=True, key=f"btn_q_kademe_{fee['id']}"):
                        n_asg = store.assign(fee["id"], k_map[q_kid]["member_ids"])
                        st.toast(f"✅ {n_asg} sporcu atandı.")
                        st.rerun(scope="fragment")
            else:
                paid = [r for r in rows if r["status"] == "Ödendi"]
                total = sum(float(r["amount"]) for r in rows)
                got = sum(float(r["amount"]) for r in paid)
                c1, c2, c3, c4 = st.columns(4)
                c1.metric("Sporcu", len(rows))
                c2.metric("Ödeyen", f"{len(paid)} / {len(rows)}")
                c3.metric("Toplanan", _fmt_tl(got))
                c4.metric("Kalan", _fmt_tl(total - got))
                st.progress(min(1.0, got / total) if total else 0.0)

                if tariffs:
                    t_counts = []
                    for t in tariffs:
                        cnt = sum(1 for r in rows if abs(float(r["amount"]) - float(t["amount"])) < 0.01)
                        t_counts.append(f"**{t['name']}** ({_fmt_tl(t['amount'])}): `{cnt} kişi`")
                    st.caption("🏷️ **Tarife Dağılımı:** " + "  ·  ".join(t_counts) + " — *Tablodaki **Tarife** sütununa tıklayarak sporcunun tarifesini değiştirebilirsiniz.*")

                f_col1, f_col2 = st.columns([2, 1])
                flt = f_col1.radio(
                    "Filtre",
                    ["Hepsi", "Ödemeyenler", "Ödeyenler"],
                    horizontal=True,
                    key="fees_pay_filter",
                    label_visibility="collapsed",
                )
                search_mem = f_col2.text_input(
                    "🔍 Sporcu Ara",
                    placeholder="🔍 Sporcu ara...",
                    key="fees_pay_search",
                    label_visibility="collapsed",
                ).strip()
                search_cf = search_mem.casefold()
                search_key = re.sub(r"[^a-z0-9_]", "_", search_cf) if search_cf else "all"

                shown = [
                    r
                    for r in rows
                    if (
                        flt == "Hepsi"
                        or (flt == "Ödemeyenler" and r["status"] != "Ödendi")
                        or (flt == "Ödeyenler" and r["status"] == "Ödendi")
                    )
                    and (not search_cf or search_cf in (r.get("member_name") or "").casefold())
                ]
                if not shown:
                    st.info("Bu filtrede / aramada kayıt bulunamadı.")
                else:
                    by_id = {r["id"]: r for r in shown}
                    ver = st.session_state.get("fees_pay_ver", 0)

                    if tariffs:
                        tariff_labels = [_tariff_option_label(t) for t in tariffs]
                        label_to_amt = {_tariff_option_label(t): float(t["amount"]) for t in tariffs}
                        curr_labels = []
                        for r in shown:
                            lbl = _match_tariff_label(r["amount"], tariffs)
                            if lbl not in label_to_amt:
                                label_to_amt[lbl] = float(r["amount"])
                                if lbl not in tariff_labels:
                                    tariff_labels.append(lbl)
                            curr_labels.append(lbl)

                        df = pd.DataFrame(
                            {
                                "Sporcu": [r["member_name"] for r in shown],
                                "Tarife": curr_labels,
                                "Tutar": [float(r["amount"]) for r in shown],
                                "Ödedi": [r["status"] == "Ödendi" for r in shown],
                                "Ödeme Tarihi": pd.to_datetime([r.get("paid_date") for r in shown]),
                            },
                            index=[r["id"] for r in shown],
                        )
                        edited = st.data_editor(
                            df,
                            hide_index=True,
                            use_container_width=True,
                            disabled=["Sporcu", "Tutar"],
                            column_config={
                                "Tarife": st.column_config.SelectboxColumn(
                                    "Tarife Seçimi",
                                    options=tariff_labels,
                                    required=True,
                                    help="Sporcunun tarifesini seçin (Kaydet'e basınca tutarı otomatik güncellenir).",
                                ),
                                "Tutar": st.column_config.NumberColumn("Tutar", format="%.2f TL"),
                                "Ödedi": st.column_config.CheckboxColumn("Ödedi"),
                                "Ödeme Tarihi": st.column_config.DateColumn("Ödeme Tarihi", format="YYYY-MM-DD"),
                            },
                            key=f"fees_editor_{fee['id']}_{flt}_{search_key}_{ver}",
                        )
                    else:
                        df = pd.DataFrame(
                            {
                                "Sporcu": [r["member_name"] for r in shown],
                                "Tutar": [float(r["amount"]) for r in shown],
                                "Ödedi": [r["status"] == "Ödendi" for r in shown],
                                "Ödeme Tarihi": pd.to_datetime([r.get("paid_date") for r in shown]),
                            },
                            index=[r["id"] for r in shown],
                        )
                        edited = st.data_editor(
                            df,
                            hide_index=True,
                            use_container_width=True,
                            disabled=["Sporcu"],
                            column_config={
                                "Tutar": st.column_config.NumberColumn(
                                    "Tutar (Kişiye Özel Düzenlenebilir)", format="%.2f TL", min_value=0.0, step=50.0
                                ),
                                "Ödedi": st.column_config.CheckboxColumn("Ödedi"),
                                "Ödeme Tarihi": st.column_config.DateColumn("Ödeme Tarihi", format="YYYY-MM-DD"),
                            },
                            key=f"fees_editor_{fee['id']}_{flt}_{search_key}_{ver}",
                        )

                    b_save, b_wa = st.columns([2, 1])
                    save_clicked = b_save.button("💾 Değişiklikleri Kaydet", type="primary", use_container_width=True, key="fees_pay_save")
                    with b_wa:
                        with st.popover("📋 Ödemeyenler (WhatsApp)", use_container_width=True):
                            unpaid_rows = [r for r in rows if r["status"] != "Ödendi"]
                            if not unpaid_rows:
                                st.success("🎉 Bu kalemde tüm sporcular ödeme yaptı!")
                            else:
                                wa_lines = [f"📢 *{fee['name']} — Ödeme Bekleyenler ({len(unpaid_rows)} kişi)*", ""]
                                for idx_u, u in enumerate(unpaid_rows, 1):
                                    wa_lines.append(f"{idx_u}. {u['member_name']} — {_fmt_tl(u['amount'])}")
                                total_rem = sum(float(u["amount"]) for u in unpaid_rows)
                                wa_lines.extend(["", f"💰 Toplam Kalan: {_fmt_tl(total_rem)}"])
                                st.caption("Sağ üstteki kopyala simgesine basıp WhatsApp grubuna yapıştırabilirsiniz:")
                                st.code("\n".join(wa_lines), language=None)

                    if save_clicked:
                        n_paid = n_unpaid = n_date = n_tariff = 0
                        for aid, row in edited.iterrows():
                            a = by_id.get(aid)
                            if a is None:
                                continue
                            was_paid = a["status"] == "Ödendi"
                            now_paid = bool(row["Ödedi"])
                            new_date = _to_date_str(row["Ödeme Tarihi"])
                            old_date = _to_date_str(a.get("paid_date"))

                            old_amt = float(a["amount"])
                            if tariffs and "Tarife" in row:
                                chosen_lbl = row["Tarife"]
                                new_amt = float(label_to_amt.get(chosen_lbl, old_amt))
                            else:
                                new_amt = float(row["Tutar"]) if pd.notna(row["Tutar"]) else old_amt

                            amt_changed = abs(new_amt - old_amt) >= 0.01

                            if now_paid and not was_paid:
                                store.mark_paid(a, fee, a["member_name"], new_date, override_amount=new_amt)
                                n_paid += 1
                                if amt_changed:
                                    n_tariff += 1
                            elif not now_paid and was_paid:
                                store.unmark_paid(a)
                                if amt_changed:
                                    store.set_assignment_amount(a, fee, new_amt)
                                    n_tariff += 1
                                n_unpaid += 1
                            else:
                                if amt_changed:
                                    store.set_assignment_amount(a, fee, new_amt)
                                    n_tariff += 1
                                if now_paid and was_paid and new_date and new_date != old_date:
                                    store.set_paid_date(a, new_date)
                                    n_date += 1

                        if n_paid or n_unpaid or n_date or n_tariff:
                            st.session_state["fees_pay_ver"] = ver + 1
                            invalidate_cb()
                            parts = []
                            if n_paid:
                                parts.append(f"{n_paid} ödendi")
                            if n_unpaid:
                                parts.append(f"{n_unpaid} geri alındı")
                            if n_tariff:
                                parts.append(f"{n_tariff} tarife/tutar güncellendi")
                            if n_date:
                                parts.append(f"{n_date} tarih güncellendi")
                            st.toast("✅ " + ", ".join(parts) + ".")
                            st.rerun(scope="fragment")
                        else:
                            st.info("Değişiklik yok.")

