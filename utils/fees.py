import sqlite3
from datetime import datetime

import pandas as pd
import requests
import streamlit as st

DEFAULT_TIME_RANGE = "05:00 - 18:15"

TABLES = {
    "members": ("ory_members", "members"),
    "fee_items": ("ory_fee_items", "fee_items"),
    "assignments": ("ory_assignments", "assignments"),
    "transactions": ("ory_transactions", "transactions"),
}

SUPABASE_SQL = """-- Supabase > SQL Editor'de BİR KEZ çalıştırın. Mevcut tablolara dokunmaz.
create table if not exists ory_members (
    id bigint generated by default as identity primary key,
    name text not null unique
);

create table if not exists ory_fee_items (
    id bigint generated by default as identity primary key,
    name text not null,
    amount numeric not null default 0,
    category_id bigint
);

create table if not exists ory_assignments (
    id bigint generated by default as identity primary key,
    member_id bigint not null references ory_members(id) on delete cascade,
    fee_item_id bigint not null references ory_fee_items(id) on delete cascade,
    amount numeric not null default 0,
    status text not null default 'Bekliyor',
    paid_date text,
    transaction_id bigint,
    unique (member_id, fee_item_id)
);

alter table ory_members disable row level security;
alter table ory_fee_items disable row level security;
alter table ory_assignments disable row level security;
"""


def _fmt_tl(x):
    try:
        return f"{float(x):,.2f}".replace(",", "X").replace(".", ",").replace("X", ".") + " TL"
    except Exception:
        return "-"


def _to_date_str(v):
    if v is None:
        return None
    try:
        if pd.isna(v):
            return None
    except Exception:
        pass
    if isinstance(v, str):
        return v[:10] if v.strip() else None
    if hasattr(v, "strftime"):
        return v.strftime("%Y-%m-%d")
    return None


@st.cache_data(ttl=120, show_spinner=False)
def _cached_fee_table(name: str, sb: bool, url: str, key: str, db_path: str):
    t = TABLES[name][0 if sb else 1]
    if sb:
        headers = {"apikey": key, "Authorization": f"Bearer {key}", "Content-Type": "application/json"}
        r = requests.get(f"{url.rstrip('/')}/rest/v1/{t}", headers=headers, params={"select": "*"}, timeout=6)
        r.raise_for_status()
        return r.json()
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    try:
        return [dict(r) for r in conn.execute(f"SELECT * FROM {t}").fetchall()]
    finally:
        conn.close()


def clear_fees_cache():
    _cached_fee_table.clear()


class FeeStore:
    """Hem Supabase hem SQLite için önbellekli ve toplu-işlem (bulk) destekli arayüz."""

    def __init__(self, use_supabase, client=None, db_path="ekonomi.db"):
        self.sb = bool(use_supabase and client is not None)
        self.c = client
        self.db_path = db_path
        self.url = client.url if self.sb else ""
        self.key = client.key if self.sb else ""

    def _t(self, name):
        return TABLES[name][0 if self.sb else 1]

    def _conn(self):
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON;")
        return conn

    def _select_cached(self, name):
        return [dict(r) for r in _cached_fee_table(name, self.sb, self.url, self.key, self.db_path)]

    def _insert(self, name, row):
        t = self._t(name)
        if self.sb:
            res = self.c._insert(t, row)
            clear_fees_cache()
            return res[0]["id"] if res else None
        cols = list(row.keys())
        conn = self._conn()
        try:
            cur = conn.execute(
                f"INSERT INTO {t} ({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)})",
                tuple(row[c] for c in cols),
            )
            conn.commit()
            clear_fees_cache()
            return cur.lastrowid
        finally:
            conn.close()

    def _insert_many(self, name, rows):
        if not rows:
            return 0
        t = self._t(name)
        if self.sb:
            res = self.c._insert(t, rows)
            clear_fees_cache()
            return len(res) if isinstance(res, list) else len(rows)
        cols = list(rows[0].keys())
        conn = self._conn()
        try:
            conn.executemany(
                f"INSERT INTO {t} ({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)})",
                [tuple(r[c] for c in cols) for r in rows],
            )
            conn.commit()
            clear_fees_cache()
            return len(rows)
        finally:
            conn.close()

    def _update(self, name, row, id_val):
        t = self._t(name)
        if self.sb:
            self.c._update(t, row, id_val)
            clear_fees_cache()
            return
        cols = list(row.keys())
        conn = self._conn()
        try:
            conn.execute(
                f"UPDATE {t} SET {', '.join(f'{c} = ?' for c in cols)} WHERE id = ?",
                tuple(row[c] for c in cols) + (id_val,),
            )
            conn.commit()
            clear_fees_cache()
        finally:
            conn.close()

    def _delete(self, name, id_val):
        t = self._t(name)
        if self.sb:
            self.c._delete(t, id_val)
            clear_fees_cache()
            return
        conn = self._conn()
        try:
            conn.execute(f"DELETE FROM {t} WHERE id = ?", (id_val,))
            conn.commit()
            clear_fees_cache()
        finally:
            conn.close()

    def ensure(self):
        cache_key = f"fees_schema_ok_{self.sb}"
        if st.session_state.get(cache_key):
            return True, ""
        if self.sb:
            try:
                for n in ("members", "fee_items", "assignments"):
                    self.c._get(self._t(n), params={"select": "id", "limit": 1})
                st.session_state[cache_key] = True
                return True, ""
            except Exception as e:
                return False, str(e)
        conn = self._conn()
        try:
            conn.executescript(
                """
                CREATE TABLE IF NOT EXISTS members (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL UNIQUE
                );
                CREATE TABLE IF NOT EXISTS fee_items (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    amount REAL NOT NULL DEFAULT 0,
                    category_id INTEGER
                );
                CREATE TABLE IF NOT EXISTS assignments (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
                    fee_item_id INTEGER NOT NULL REFERENCES fee_items(id) ON DELETE CASCADE,
                    amount REAL NOT NULL DEFAULT 0,
                    status TEXT NOT NULL DEFAULT 'Bekliyor',
                    paid_date TEXT,
                    transaction_id INTEGER,
                    UNIQUE (member_id, fee_item_id)
                );
                """
            )
            conn.commit()
        finally:
            conn.close()
        st.session_state[cache_key] = True
        return True, ""

    def members(self):
        return sorted(self._select_cached("members"), key=lambda m: (m["name"] or "").casefold())

    def add_members(self, names):
        existing = {m["name"].strip().casefold() for m in self.members()}
        to_add = []
        for raw in names:
            n = " ".join(str(raw).split())
            if n and n.casefold() not in existing:
                to_add.append({"name": n})
                existing.add(n.casefold())
        return self._insert_many("members", to_add)

    def delete_members(self, member_ids):
        id_set = set(member_ids)
        all_asg = [a for a in self._select_cached("assignments") if a["member_id"] in id_set]
        tx_changed = False
        for a in all_asg:
            if a.get("transaction_id"):
                tx_changed = True
            self._remove_assignment_and_tx(a)
        for mid in member_ids:
            self._delete("members", mid)
        clear_fees_cache()
        return tx_changed

    def fee_items(self):
        return sorted(self._select_cached("fee_items"), key=lambda f: (f["name"] or "").casefold())

    def add_fee_item(self, name, amount, category_id):
        return self._insert(
            "fee_items", {"name": name.strip(), "amount": float(amount), "category_id": category_id}
        )

    def update_fee_item(self, fee_id, name, amount, category_id, update_unpaid=True):
        self._update(
            "fee_items",
            {"name": name.strip(), "amount": float(amount), "category_id": category_id},
            fee_id,
        )
        if update_unpaid:
            for a in self.assignments(fee_id):
                if a.get("status") != "Ödendi":
                    self._update("assignments", {"amount": float(amount)}, a["id"])
        clear_fees_cache()

    def delete_fee_item(self, fee_id):
        for a in self.assignments(fee_id):
            self._remove_assignment_and_tx(a)
        self._delete("fee_items", fee_id)
        clear_fees_cache()

    def assignments(self, fee_id):
        names = {m["id"]: m["name"] for m in self.members()}
        rows = [dict(r) for r in self._select_cached("assignments") if r["fee_item_id"] == fee_id]
        for r in rows:
            r["member_name"] = names.get(r["member_id"], "?")
        rows.sort(key=lambda r: (r["member_name"] or "").casefold())
        return rows

    def assign(self, fee_id, member_ids):
        fee = next((f for f in self.fee_items() if f["id"] == fee_id), None)
        if not fee:
            return 0
        have = {a["member_id"] for a in self.assignments(fee_id)}
        to_add = [
            {
                "member_id": mid,
                "fee_item_id": fee_id,
                "amount": float(fee["amount"]),
                "status": "Bekliyor",
                "paid_date": None,
                "transaction_id": None,
            }
            for mid in member_ids
            if mid not in have
        ]
        return self._insert_many("assignments", to_add)

    def remove_assignments(self, assignment_ids):
        id_set = set(assignment_ids)
        tx_changed = False
        for a in self._select_cached("assignments"):
            if a["id"] in id_set:
                if a.get("transaction_id"):
                    tx_changed = True
                self._remove_assignment_and_tx(a)
        clear_fees_cache()
        return tx_changed

    def _remove_assignment_and_tx(self, a):
        if a.get("transaction_id"):
            try:
                self._delete("transactions", a["transaction_id"])
            except Exception:
                pass
        self._delete("assignments", a["id"])

    def mark_paid(self, a, fee, member_name, date_str=None):
        date_str = date_str or datetime.now().strftime("%Y-%m-%d")
        tx_id = self._insert(
            "transactions",
            {
                "date": date_str,
                "category_id": fee["category_id"],
                "amount": float(a["amount"]),
                "description": f"{fee['name']} – {member_name}",
                "time_range": DEFAULT_TIME_RANGE,
            },
        )
        self._update(
            "assignments",
            {"status": "Ödendi", "paid_date": date_str, "transaction_id": tx_id},
            a["id"],
        )

    def set_paid_date(self, a, date_str):
        if a.get("transaction_id"):
            self._update("transactions", {"date": date_str}, a["transaction_id"])
        self._update("assignments", {"paid_date": date_str}, a["id"])

    def unmark_paid(self, a):
        if a.get("transaction_id"):
            try:
                self._delete("transactions", a["transaction_id"])
            except Exception:
                pass
        self._update(
            "assignments",
            {"status": "Bekliyor", "paid_date": None, "transaction_id": None},
            a["id"],
        )


@st.fragment
def render_fees_page(store, categories, invalidate_cb, today_date):
    ok, err = store.ensure()
    if not ok:
        st.error("Ücret takibi tabloları Supabase'de henüz yok (ya da bağlantı kurulamadı).")
        st.code(SUPABASE_SQL, language="sql")
        st.caption(f"Teknik ayrıntı: {err}")
        return

    income_cats = [c for c in categories if c.get("type") == "Gelir"]
    tab_pay, tab_fee, tab_mem = st.tabs(["✅ Ödeme Takibi", "🧾 Ücret Kalemleri", "👥 Sporcu Havuzu"])

    # ------------------------------------------------ 1. Ödeme Takibi
    with tab_pay:
        items = store.fee_items()
        if not items:
            st.info("Henüz ücret kalemi yok. **🧾 Ücret Kalemleri** sekmesinden ekleyin.")
        else:
            fee = st.selectbox(
                "Ücret kalemi seçin",
                items,
                format_func=lambda f: f"{f['name']} — {_fmt_tl(f['amount'])}",
                key="fees_pay_item",
            )
            rows = store.assignments(fee["id"])
            if not rows:
                st.info("Bu kaleme henüz sporcu atanmamış. **🧾 Ücret Kalemleri** sekmesinden atayabilirsiniz.")
            else:
                paid = [r for r in rows if r["status"] == "Ödendi"]
                total = sum(float(r["amount"]) for r in rows)
                got = sum(float(r["amount"]) for r in paid)
                c1, c2, c3, c4 = st.columns(4)
                c1.metric("Sporcu", len(rows))
                c2.metric("Ödeyen", f"{len(paid)} / {len(rows)}")
                c3.metric("Toplanan", _fmt_tl(got))
                c4.metric("Kalan", _fmt_tl(total - got))
                st.progress(min(1.0, got / total) if total else 0.0)

                flt = st.radio(
                    "Filtre", ["Hepsi", "Ödemeyenler", "Ödeyenler"], horizontal=True, key="fees_pay_filter", label_visibility="collapsed"
                )
                shown = [
                    r for r in rows
                    if flt == "Hepsi"
                    or (flt == "Ödemeyenler" and r["status"] != "Ödendi")
                    or (flt == "Ödeyenler" and r["status"] == "Ödendi")
                ]
                if not shown:
                    st.success("Bu filtrede kayıt yok.")
                else:
                    by_id = {r["id"]: r for r in shown}
                    df = pd.DataFrame(
                        {
                            "Sporcu": [r["member_name"] for r in shown],
                            "Tutar": [float(r["amount"]) for r in shown],
                            "Ödedi": [r["status"] == "Ödendi" for r in shown],
                            "Ödeme Tarihi": pd.to_datetime([r.get("paid_date") for r in shown]),
                        },
                        index=[r["id"] for r in shown],
                    )
                    ver = st.session_state.get("fees_pay_ver", 0)
                    edited = st.data_editor(
                        df,
                        hide_index=True,
                        use_container_width=True,
                        disabled=["Sporcu", "Tutar"],
                        column_config={
                            "Tutar": st.column_config.NumberColumn(format="%.2f TL"),
                            "Ödedi": st.column_config.CheckboxColumn("Ödedi"),
                            "Ödeme Tarihi": st.column_config.DateColumn("Ödeme Tarihi", format="YYYY-MM-DD"),
                        },
                        key=f"fees_editor_{fee['id']}_{flt}_{ver}",
                    )

                    if st.button("💾 Değişiklikleri Kaydet", type="primary", key="fees_pay_save"):
                        n_paid = n_unpaid = n_date = 0
                        for aid, row in edited.iterrows():
                            a = by_id.get(aid)
                            if a is None:
                                continue
                            was_paid = a["status"] == "Ödendi"
                            now_paid = bool(row["Ödedi"])
                            new_date = _to_date_str(row["Ödeme Tarihi"])
                            old_date = _to_date_str(a.get("paid_date"))
                            if now_paid and not was_paid:
                                store.mark_paid(a, fee, a["member_name"], new_date)
                                n_paid += 1
                            elif not now_paid and was_paid:
                                store.unmark_paid(a)
                                n_unpaid += 1
                            elif now_paid and was_paid and new_date and new_date != old_date:
                                store.set_paid_date(a, new_date)
                                n_date += 1
                        if n_paid or n_unpaid or n_date:
                            st.session_state["fees_pay_ver"] = ver + 1
                            invalidate_cb()
                            st.toast(f"✅ {n_paid} ödendi, {n_unpaid} geri alındı, {n_date} tarih güncellendi.")
                            st.rerun(scope="fragment")
                        else:
                            st.info("Değişiklik yok.")

    # ------------------------------------------------ 2. Ücret Kalemleri
    with tab_fee:
        members = store.members()
        mem_map = {m["id"]: m["name"] for m in members}
        fee_list = store.fee_items()

        h_col1, h_col2 = st.columns([3, 1])
        h_col1.markdown(f"#### 🧾 Ücret Kalemleri ({len(fee_list)})")
        show_new_fee = st.session_state.get("show_new_fee_form", False)
        if h_col2.button("✖️ Kapat" if show_new_fee else "➕ Yeni Kalem Ekle", key="toggle_new_fee_btn", type="secondary" if show_new_fee else "primary", use_container_width=True):
            st.session_state["show_new_fee_form"] = not show_new_fee
            st.rerun(scope="fragment")

        if st.session_state.get("show_new_fee_form", False):
            if not income_cats:
                st.warning("Önce Kategori Yönetimi'nden bir **Gelir** kategorisi oluşturun.")
            else:
                with st.form("fees_new_item", clear_on_submit=True):
                    f1, f2 = st.columns([2, 1])
                    name = f1.text_input("Kalem Adı", placeholder="Örn: Kırmızı tişört")
                    amount = f2.number_input("Birim Fiyat (TL)", min_value=0.0, step=50.0, format="%.2f")
                    cat = st.selectbox(
                        "Gelir kategorisi",
                        income_cats,
                        format_func=lambda c: f"{c['emoji']} {c['name']}",
                    )
                    everyone = st.checkbox("Tüm sporculara ata", value=True)
                    chosen = st.multiselect(
                        "…veya sadece seçilen sporculara ata",
                        list(mem_map.keys()),
                        format_func=lambda i: mem_map[i],
                    )
                    if st.form_submit_button("✅ Kalemi Oluştur", type="primary"):
                        if not name.strip():
                            st.error("Ad boş olamaz.")
                        else:
                            fid = store.add_fee_item(name, amount, cat["id"])
                            ids = list(mem_map.keys()) if everyone else chosen
                            n = store.assign(fid, ids) if ids else 0
                            st.session_state["show_new_fee_form"] = False
                            st.toast(f"✅ '{name.strip()}' eklendi ({n} sporcu).")
                            st.rerun(scope="fragment")

        if not fee_list:
            st.info("Henüz kayıtlı bir ücret kalemi yok. Sağ üstteki **➕ Yeni Kalem Ekle** butonuna basarak oluşturabilirsiniz.")
        else:
            for f in fee_list:
                asg = store.assignments(f["id"])
                paid_n = sum(1 for a in asg if a["status"] == "Ödendi")
                with st.expander(f"{f['name']} — {_fmt_tl(f['amount'])}  ·  {paid_n}/{len(asg)} ödedi"):
                    assigned_ids = {a["member_id"] for a in asg}
                    free = [m for m in members if m["id"] not in assigned_ids]
                    if free:
                        add_sel = st.multiselect(
                            "Sorumlu sporcu ekle", [m["id"] for m in free], format_func=lambda i: mem_map[i], key=f"fees_add_{f['id']}"
                        )
                        b1, b2 = st.columns(2)
                        if b1.button("➕ Seçilenleri ata", key=f"fees_addbtn_{f['id']}", use_container_width=True) and add_sel:
                            store.assign(f["id"], add_sel)
                            st.toast("✅ Sporcular atandı.")
                            st.rerun(scope="fragment")
                        if b2.button("➕ Kalan herkesi ata", key=f"fees_addall_{f['id']}", use_container_width=True):
                            store.assign(f["id"], [m["id"] for m in free])
                            st.toast("✅ Tüm sporcular atandı.")
                            st.rerun(scope="fragment")

                    if asg:
                        rm_map = {a["id"]: a["member_name"] + (" (ödedi)" if a["status"] == "Ödendi" else "") for a in asg}
                        rm_sel = st.multiselect(
                            "Sorumluluktan çıkar",
                            list(rm_map.keys()),
                            format_func=lambda i: rm_map[i],
                            key=f"fees_rm_{f['id']}",
                        )
                        if rm_sel and st.button("➖ Seçilenleri çıkar", key=f"fees_rmbtn_{f['id']}"):
                            tx_ch = store.remove_assignments(rm_sel)
                            if tx_ch:
                                invalidate_cb()
                            st.toast("✅ Atamalar kaldırıldı.")
                            st.rerun(scope="fragment")

                    with st.popover("✏️ Kalemi Düzenle / Sil"):
                        with st.form(f"fees_edit_{f['id']}"):
                            n_name = st.text_input("Ad", value=f["name"])
                            n_amount = st.number_input("Fiyat (TL)", min_value=0.0, step=50.0, format="%.2f", value=float(f["amount"]))
                            cur_idx = next((i for i, c in enumerate(income_cats) if c["id"] == f["category_id"]), 0)
                            n_cat = st.selectbox(
                                "Gelir kategorisi",
                                income_cats,
                                index=cur_idx,
                                format_func=lambda c: f"{c['emoji']} {c['name']}",
                            ) if income_cats else None
                            upd = st.checkbox("Ödenmemiş sporcuların tutarını da güncelle", value=True)
                            if st.form_submit_button("Değişiklikleri Kaydet", type="primary") and n_cat:
                                store.update_fee_item(f["id"], n_name, n_amount, n_cat["id"], upd)
                                st.toast("✅ Kalem güncellendi.")
                                st.rerun(scope="fragment")
                        if st.button("🗑️ Bu Kalemi Tamamen Sil", key=f"fees_delbtn_{f['id']}", use_container_width=True):
                            store.delete_fee_item(f["id"])
                            invalidate_cb()
                            st.toast("🗑️ Kalem silindi.")
                            st.rerun(scope="fragment")

    # ------------------------------------------------ 3. Sporcu Havuzu
    with tab_mem:
        members = store.members()
        m_col1, m_col2 = st.columns([3, 1])
        m_col1.markdown(f"#### 👥 Kayıtlı Sporcular ({len(members)})")
        show_new_mem = st.session_state.get("show_new_mem_form", False)
        if m_col2.button("✖️ Kapat" if show_new_mem else "➕ Sporcu Ekle", key="toggle_new_mem_btn", type="secondary" if show_new_mem else "primary", use_container_width=True):
            st.session_state["show_new_mem_form"] = not show_new_mem
            st.rerun(scope="fragment")

        if st.session_state.get("show_new_mem_form", False):
            with st.form("fees_new_members", clear_on_submit=True):
                txt = st.text_area(
                    "Her satıra bir isim yazın (toplu yapıştırabilirsiniz)",
                    height=110,
                    placeholder="Ahmet Yılmaz\nAyşe Demir",
                )
                if st.form_submit_button("✅ Sporcuları Kaydet", type="primary"):
                    n = store.add_members(txt.splitlines())
                    if n:
                        st.session_state["show_new_mem_form"] = False
                        st.toast(f"✅ {n} sporcu eklendi.")
                        st.rerun(scope="fragment")
                    else:
                        st.info("Yeni isim bulunamadı (zaten kayıtlı olabilir).")

        if members:
            st.dataframe(pd.DataFrame({"Sporcu Adı": [m["name"] for m in members]}), hide_index=True, use_container_width=True)
            with st.popover("🗑️ Sporcu Sil"):
                mem_map = {m["id"]: m["name"] for m in members}
                del_sel = st.multiselect("Silinecek sporcular", list(mem_map.keys()), format_func=lambda i: mem_map[i])
                if st.button("Seçilen Sporcuları Sil", type="primary", disabled=not del_sel):
                    tx_ch = store.delete_members(del_sel)
                    if tx_ch:
                        invalidate_cb()
                    st.toast("🗑️ Seçilen sporcular silindi.")
                    st.rerun(scope="fragment")
        else:
            st.info("Henüz sporcu yok. Sağ üstteki **➕ Sporcu Ekle** butonuna basarak ekleyebilirsiniz.")
